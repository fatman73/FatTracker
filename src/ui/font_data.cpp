struct Table {
    uint8_t g[128][8];
};

constexpr Table build() {
    Table t{};
    for (const Art& a : kArt) {
        for (int r = 0; r < 8; ++r) {
            uint8_t v = 0;
            for (int c = 0; c < 8; ++c)
                if (a.rows[r * 8 + c] == '#') v |= (uint8_t)(0x80 >> c);
            t.g[a.code][r] = v;
        }
    }
    return t;
}

